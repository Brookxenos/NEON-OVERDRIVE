export const DEFAULT_CAR_ID: CarId = 'sunshine_muscle';

export function isValidCarId(value: unknown): value is CarId {
  return CAR_CATALOG.some((car) => car.id === value);
}

export function getCarSpec(id: CarId): CarSpec {
  return CAR_CATALOG.find((car) => car.id === id) ?? CAR_CATALOG[0];
}

export function getNextLockedCar(unlockedCars: readonly CarId[]): CarSpec | null {
  const unlockedSet = new Set(unlockedCars);
  for (const car of CAR_CATALOG) {
    if (!unlockedSet.has(car.id)) {
      return car;
    }
  }
  return null;
}
